'use strict';

// Release signing keys for automatic updates.
//
//   node scripts/update-keys.cjs generate [--dir <folder>]
//
// Creates the manifest key and the rescue (revocation) key. Private keys are
// written outside the repository, readable by the current account only, and
// never overwritten. Their public halves are added to src/update-keys.cjs.
// Keep two offline copies of the private key folder: without the manifest key
// installed copies of Nacre can no longer update themselves.

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');

const root = path.join(__dirname, '..');
const keysModule = path.join(root, 'src', 'update-keys.cjs');

function argument(name, fallback) {
  const index = process.argv.indexOf(name);
  return index === -1 ? fallback : process.argv[index + 1];
}

function defaultKeyDirectory() {
  return path.join(os.homedir(), '.nacre-release-keys');
}

function restrictToCurrentAccount(target) {
  if (process.platform === 'win32') {
    const who = execFileSync('whoami.exe', ['/user', '/fo', 'csv', '/nh'], { encoding: 'utf8', windowsHide: true });
    const sid = /S-1-(?:\d+-)+\d+/i.exec(who)?.[0];
    if (!sid) throw new Error('Compte Windows introuvable.');
    execFileSync('icacls.exe', [target, '/inheritance:r', '/grant:r', `*${sid}:(OI)(CI)F`], { windowsHide: true, stdio: 'ignore' });
  } else {
    fs.chmodSync(target, 0o700);
  }
}

function writeKeysModule(keys) {
  const body = keys.map((key) => `  Object.freeze({ keyId: '${key.keyId}', role: '${key.role}', spki: '${key.spki}' })`).join(',\n');
  fs.writeFileSync(keysModule, `'use strict';

// Public keys trusted for automatic updates (generated by
// scripts/update-keys.cjs). role 'manifest' signs update manifests; role
// 'revocation' only signs key revocations. See SECURITY.md for rotation.
module.exports = Object.freeze([
${body}
]);
`);
}

function generate() {
  const directory = path.resolve(argument('--dir', defaultKeyDirectory()));
  if (!path.relative(root, directory).startsWith('..')) throw new Error('Les clés privées doivent rester hors du dépôt.');
  const existing = require(keysModule);
  if (existing.length) throw new Error('Des clés publiques sont déjà intégrées. Une rotation se prépare à la main (voir SECURITY.md).');
  const year = new Date().getUTCFullYear();
  const plan = [
    { keyId: `nacre-${year}a`, role: 'manifest' },
    { keyId: `nacre-rescue-${year}a`, role: 'revocation' }
  ];
  fs.mkdirSync(directory, { recursive: true });
  restrictToCurrentAccount(directory);
  const keys = plan.map(({ keyId, role }) => {
    const file = path.join(directory, `${keyId}.pem`);
    const { publicKey, privateKey } = crypto.generateKeyPairSync('ed25519');
    fs.writeFileSync(file, privateKey.export({ type: 'pkcs8', format: 'pem' }), { flag: 'wx', mode: 0o600 });
    return { keyId, role, spki: publicKey.export({ type: 'spki', format: 'der' }).toString('base64') };
  });
  writeKeysModule(keys);
  process.stdout.write(`Clés privées : ${directory}\nClés publiques ajoutées à src/update-keys.cjs.\nFais maintenant deux copies hors ligne de ce dossier.\n`);
}

function loadPrivateKey(keyId, directory = argument('--keys', defaultKeyDirectory())) {
  return crypto.createPrivateKey(fs.readFileSync(path.join(directory, `${keyId}.pem`)));
}

if (require.main === module) {
  try {
    if (process.argv[2] === 'generate') generate();
    else throw new Error('Usage : node scripts/update-keys.cjs generate [--dir <dossier>]');
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}

module.exports = { defaultKeyDirectory, loadPrivateKey };
